/// Turns a `GenerationPlan` into Swift source.
///
/// Every decision was made by the plan. This file only spells it, which is
/// why it has no failure path: a plan that reached here compiles.

import Foundation

/// Words Swift will not accept as an identifier without backticks.
private let reserved: Set<String> = [
    "associatedtype", "class", "deinit", "enum", "extension", "fileprivate", "func",
    "import", "init", "inout", "internal", "let", "open", "operator", "private",
    "precedencegroup", "protocol", "public", "rethrows", "static", "struct",
    "subscript", "typealias", "var", "break", "case", "catch", "continue",
    "default", "defer", "do", "else", "fallthrough", "for", "guard", "if", "in",
    "repeat", "return", "throw", "switch", "where", "while", "Any", "as", "await",
    "false", "is", "nil", "self", "Self", "super", "throws", "true", "try",
]

private let types: [String: String] = [
    "STRING": "String",
    "NUMBER": "some LocalazeNumber",
    "DATETIME": "Date",
]

private func escape(_ identifier: String) -> String {
    reserved.contains(identifier) ? "`\(identifier)`" : identifier
}

/// The Swift source for `plan`.
public func emitSwift(_ plan: GenerationPlan) -> String {
    var out = ""
    header(&out, plan)
    type(&out, plan)
    signature(&out, plan)
    plurals(&out, plan)
    compiledIn(&out, plan)
    return out
}

private func line(_ out: inout String, _ text: String = "") {
    out += text + "\n"
}

private func header(_ out: inout String, _ plan: GenerationPlan) {
    line(&out, "// GENERATED BY LOCALAZE — DO NOT EDIT.")
    line(&out, "// Regenerate with `swift run localaze-generate`. Hand edits are lost.")
    line(&out, "//")
    line(&out, "// environment: \(comment(plan.environment))")
    line(&out, "// version:     \(comment(plan.version))")
    line(&out, "// hash:        \(comment(plan.contentHash))")
    line(&out, "// source:      \(comment(plan.sourceLanguage))")
    line(&out)
    line(&out, "import Foundation")
    line(&out, "import Localaze")
    line(&out)
}

private func type(_ out: inout String, _ plan: GenerationPlan) {
    let locales = plan.languages.map(literal).joined(separator: ", ")
    line(&out, "/// Typed translations, generated from release \(comment(plan.version)).")
    line(&out, "///")
    line(&out, "/// Every accessor is typed: a message that selects on a count cannot be")
    line(&out, "/// called without one, and the compiler checks it.")
    line(&out, "public struct Localaze: Sendable {")
    line(&out, "    /// The runtime behind these accessors, for the update machinery.")
    line(&out, "    public let runtime: LocalazeRuntime")
    line(&out)
    line(&out, "    /// The languages this release carries, source first.")
    line(&out, "    public static let supportedLocales: [String] = [\(locales)]")
    line(&out)
    line(&out, "    public static let sourceLocale = \(literal(plan.sourceLanguage))")
    line(&out)
    line(&out, "    /// The release this code was generated from. The update policy")
    line(&out, "    /// compares every fetched catalog against it.")
    line(&out, "    public static let generatedFrom = \(literal(plan.version))")
    line(&out)
    line(&out, "    public static let contentHash = \(literal(plan.contentHash))")
    line(&out)
    line(&out, "    /// Translations for `locale`. A locale this release does not carry")
    line(&out, "    /// starts from the source language's compiled-in catalog.")
    line(&out, "    public static func forLocale(_ locale: String, config: LocalazeConfig) -> Localaze {")
    line(&out, "        Localaze(runtime: LocalazeRuntime(")
    line(&out, "            locale: locale,")
    line(&out, "            config: config,")
    line(&out, "            signature: _signature,")
    line(&out, "            compiledIn: _compiledIn[locale] ?? _compiledIn[sourceLocale]!,")
    line(&out, "            pluralResolver: { _plural(locale, $0) }))")
    line(&out, "    }")

    for key in plan.keys {
        line(&out)
        accessor(&out, key)
    }
    line(&out, "}")
    line(&out)
}

private func accessor(_ out: inout String, _ key: PlannedKey) {
    if !key.preview.isEmpty {
        line(&out, "    /// `\(comment(key.preview).replacingOccurrences(of: "`", with: "'"))`")
    }
    if let selector = key.selector {
        if !key.preview.isEmpty { line(&out, "    ///") }
        line(&out, "    /// Selects on `\(selector)`, so it cannot be called without it.")
    }

    let name = escape(key.accessor)
    if key.params.isEmpty {
        line(&out, "    public var \(name): String { self.runtime.render(\(literal(key.key))) }")
        return
    }

    let params = key.params
        .map { "\(escape($0.identifier)): \(types[$0.type]!)" }
        .joined(separator: ", ")
    let args = key.params
        .map { "\(literal($0.name)): \(escape($0.identifier))" }
        .joined(separator: ", ")

    var call = "self.runtime.render(\(literal(key.key)), args: [\(args)]"
    if let selector = key.selector,
       let param = key.params.first(where: { $0.name == selector }) {
        call += ", selector: \(escape(param.identifier)).localazeValue"
    }
    call += ")"

    line(&out, "    public func \(name)(\(params)) -> String {")
    line(&out, "        \(call)")
    line(&out, "    }")
}

// File-private helpers in the generated file start with an underscore. No
// accessor can, so a key named `plural` or `signature` cannot shadow them.

private func signature(_ out: inout String, _ plan: GenerationPlan) {
    line(&out, "// MARK: - Signature")
    line(&out, "// Names and types. A fetched catalog is refused unless every key here is")
    line(&out, "// present and every parameter still matches.")
    line(&out)
    line(&out, "private let _signature = LocalazeSignature(of: [")
    for key in plan.keys {
        let params = key.params
            .map { "(\(literal($0.name)), \(literal($0.type)))" }
            .joined(separator: ", ")
        line(&out, "    \(literal(key.key)): [\(params)],")
    }
    line(&out, "] as [String: [(String, String)]])")
    line(&out)
}

private func plurals(_ out: inout String, _ plan: GenerationPlan) {
    line(&out, "// MARK: - Plural rules")
    line(&out, "// Each language's CLDR rules, compiled by the server and published in the")
    line(&out, "// manifest. No CLDR data ships and no MF2 is parsed on device.")
    line(&out)
    line(&out, "private func _plural(_ locale: String, _ value: Double) -> String? {")
    line(&out, "    switch locale {")
    for plural in plan.plurals {
        line(&out, "    case \(literal(plural.language)): return \(resolverName(plural.language))(value)")
    }
    line(&out, "    default: return nil")
    line(&out, "    }")
    line(&out, "}")

    for plural in plan.plurals {
        line(&out)
        resolver(&out, plural)
    }
    line(&out)
}

private func resolver(_ out: inout String, _ plural: PlannedPlural) {
    let name = resolverName(plural.language)
    if plural.categories.isEmpty {
        line(&out, "private func \(name)(_ value: Double) -> String? { nil }")
        return
    }

    let usesV = plural.uses("v")
    let usesI = plural.uses("i")

    line(&out, "private func \(name)(_ value: Double) -> String? {")
    line(&out, "    let n = abs(value)")
    line(&out, "    guard n.isFinite, n < 1e15 else { return nil }")
    if usesI { line(&out, "    let i = Int(n.rounded(.down))") }
    if usesV { line(&out, "    let v = n == n.rounded(.down) ? 0 : 1") }
    line(&out)
    for (category, condition) in plural.categories {
        line(&out, "    if \(swiftCondition(condition)) { return \(literal(category)) }")
    }
    line(&out, "    return nil")
    line(&out, "}")
}

/// `(n % k)` becomes `n.truncatingRemainder(dividingBy: k)`: Swift has no `%`
/// on floating-point values. Everything else is valid Swift as written.
func swiftCondition(_ condition: String) -> String {
    var result = condition
    while let range = result.range(of: #"\(n % (\d+)\)"#, options: .regularExpression) {
        let match = String(result[range])
        let divisor = match.dropFirst(5).dropLast()
        result.replaceSubrange(range, with: "n.truncatingRemainder(dividingBy: \(divisor))")
    }
    return result
}

private func compiledIn(_ out: inout String, _ plan: GenerationPlan) {
    line(&out, "// MARK: - Compiled-in catalogs")
    line(&out, "// The floor. An app whose asset is missing or unreadable still renders")
    line(&out, "// text rather than key names.")
    line(&out)
    line(&out, "private let _compiledIn: [String: String] = [")
    for language in plan.languages {
        line(&out, "    \(literal(language)): \(literal(plan.catalogs[language]!)),")
    }
    line(&out, "]")
}

/// `pt-BR` becomes `_pluralPtBr`.
private func resolverName(_ language: String) -> String {
    let segments = language.split(whereSeparator: { $0 == "-" || $0 == "_" })
    return "_plural" + segments.map { $0.prefix(1).uppercased() + $0.dropFirst().lowercased() }.joined()
}

/// A Swift string literal holding exactly `value`.
func literal(_ value: String) -> String {
    var out = "\""
    for scalar in value.unicodeScalars {
        switch scalar {
        case "\\": out += "\\\\"
        case "\"": out += "\\\""
        case "\n": out += "\\n"
        case "\r": out += "\\r"
        case "\t": out += "\\t"
        default:
            if scalar.value < 0x20 || scalar.value == 0x7F {
                out += "\\u{\(String(scalar.value, radix: 16))}"
            } else {
                out.unicodeScalars.append(scalar)
            }
        }
    }
    return out + "\""
}

/// Text safe inside a `//` or `///` comment: one line, nothing else.
private func comment(_ value: String) -> String {
    var out = ""
    var pendingSpace = false
    for scalar in value.unicodeScalars {
        if scalar == "\r" || scalar == "\n" || scalar.value == 0x2028 || scalar.value == 0x2029 {
            pendingSpace = true
            continue
        }
        if pendingSpace { out += " "; pendingSpace = false }
        out.unicodeScalars.append(scalar)
    }
    return pendingSpace ? out + " " : out
}
